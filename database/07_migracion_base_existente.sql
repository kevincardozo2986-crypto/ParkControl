-- ========================================
-- PARKCONTROL - Migración de la base existente (Bloque 7 -> integración FE/BE)
-- ========================================
-- Ejecutar UNA vez sobre la base de Supabase que ya tiene las 7 tablas
-- originales (roles, usuarios, conductores, vehiculos, espacios, estancias, pagos).
-- Es idempotente: puede repetirse sin duplicar objetos.
--
-- Cambios:
--   1. usuarios.version_sesion (revocación de JWT)
--   2. conductores.usuario_id (vínculo cuenta <-> ficha, base de BOLA/IDOR)
--   3. tablas password_reset_tokens y codigos_recuperacion
--   4. roles operador y conductor; cuentas con rol 'usuario' pasan a 'conductor'
-- ========================================

BEGIN;

-- 1. Versión de sesión
ALTER TABLE public.usuarios
ADD COLUMN IF NOT EXISTS version_sesion INTEGER NOT NULL DEFAULT 0;

-- 2. Vínculo conductor -> cuenta
ALTER TABLE public.conductores
ADD COLUMN IF NOT EXISTS usuario_id BIGINT;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'conductores_usuario_id_fkey'
  ) THEN
    ALTER TABLE public.conductores
    ADD CONSTRAINT conductores_usuario_id_fkey
    FOREIGN KEY (usuario_id) REFERENCES public.usuarios(id) ON DELETE SET NULL;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'conductores_usuario_id_key'
  ) THEN
    ALTER TABLE public.conductores
    ADD CONSTRAINT conductores_usuario_id_key UNIQUE (usuario_id);
  END IF;
END $$;

-- 3. Tablas de recuperación
CREATE TABLE IF NOT EXISTS public.password_reset_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
    administrador_id BIGINT NOT NULL REFERENCES public.usuarios(id),
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_expiracion TIMESTAMPTZ NOT NULL,
    fecha_uso TIMESTAMPTZ,
    CONSTRAINT ck_reset_expiracion CHECK (fecha_expiracion > fecha_creacion)
);

CREATE INDEX IF NOT EXISTS idx_reset_usuario ON public.password_reset_tokens(usuario_id);
CREATE INDEX IF NOT EXISTS idx_reset_expiracion ON public.password_reset_tokens(fecha_expiracion);

CREATE TABLE IF NOT EXISTS public.codigos_recuperacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
    codigo_hash VARCHAR(64) NOT NULL UNIQUE,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_uso TIMESTAMPTZ,
    CONSTRAINT ck_codigos_fecha_uso CHECK (fecha_uso IS NULL OR fecha_uso >= fecha_creacion)
);

CREATE INDEX IF NOT EXISTS idx_codigos_recuperacion_usuario ON public.codigos_recuperacion(usuario_id);

-- 4. Roles
INSERT INTO public.roles (nombre, descripcion, activo) VALUES
('operador',  'Registra entradas, salidas y pagos en la portería del parqueadero', TRUE),
('conductor', 'Consulta únicamente sus vehículos, estancias y pagos', TRUE)
ON CONFLICT (nombre) DO NOTHING;

UPDATE public.usuarios
SET rol_id = (SELECT id FROM public.roles WHERE nombre = 'conductor'),
    version_sesion = version_sesion + 1
WHERE rol_id = (SELECT id FROM public.roles WHERE nombre = 'usuario');

UPDATE public.roles SET activo = FALSE WHERE nombre = 'usuario';

-- 5. Seguridad de las tablas nuevas
ALTER TABLE public.password_reset_tokens ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.codigos_recuperacion ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.password_reset_tokens FROM PUBLIC, anon, authenticated;
REVOKE ALL ON TABLE public.codigos_recuperacion FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM PUBLIC, anon, authenticated;

COMMIT;

-- Comprobación rápida
SELECT r.nombre AS rol, r.activo, COUNT(u.id) AS cuentas
FROM public.roles r
LEFT JOIN public.usuarios u ON u.rol_id = r.id
GROUP BY r.nombre, r.activo
ORDER BY r.nombre;
