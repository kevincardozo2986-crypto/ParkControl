
-- BLOQUE 7.1 - PARKCONTROL
-- Esquema relacional PostgreSQL

-- 1. ROLES
CREATE TABLE IF NOT EXISTS public.roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(30) NOT NULL UNIQUE,
    descripcion TEXT,
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

-- 2. USUARIOS
CREATE TABLE IF NOT EXISTS public.usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    email VARCHAR(255) NOT NULL,
    password_hash TEXT NOT NULL,
    rol_id BIGINT NOT NULL REFERENCES public.roles(id),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_registro TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_usuarios_email
ON public.usuarios (LOWER(email));

-- 3. CONDUCTORES
CREATE TABLE IF NOT EXISTS public.conductores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    documento VARCHAR(30) NOT NULL UNIQUE,
    telefono VARCHAR(30),
    correo VARCHAR(255)
);

-- 4. VEHICULOS
CREATE TABLE IF NOT EXISTS public.vehiculos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    placa VARCHAR(15) NOT NULL UNIQUE,
    tipo VARCHAR(20) NOT NULL
        CHECK (tipo IN ('carro', 'moto')),
    marca VARCHAR(80),
    color VARCHAR(50),
    conductor_id BIGINT NOT NULL
        REFERENCES public.conductores(id)
        ON DELETE RESTRICT,
    CONSTRAINT placa_mayuscula CHECK (placa = UPPER(placa))
);

-- 5. ESPACIOS
CREATE TABLE IF NOT EXISTS public.espacios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero VARCHAR(20) NOT NULL UNIQUE,
    tipo VARCHAR(20) NOT NULL
        CHECK (tipo IN ('carro', 'moto')),
    estado VARCHAR(20) NOT NULL DEFAULT 'disponible'
        CHECK (estado IN ('disponible', 'ocupado')),
    ubicacion VARCHAR(120)
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_espacios_numero
ON public.espacios (LOWER(numero));

-- 6. ESTANCIAS
CREATE TABLE IF NOT EXISTS public.estancias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehiculo_id BIGINT NOT NULL
        REFERENCES public.vehiculos(id)
        ON DELETE RESTRICT,
    espacio_id BIGINT NOT NULL
        REFERENCES public.espacios(id)
        ON DELETE RESTRICT,
    fecha_hora_entrada TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_hora_salida TIMESTAMPTZ,
    estado VARCHAR(20) NOT NULL DEFAULT 'activa'
        CHECK (estado IN ('activa', 'finalizada')),
    tiempo_permanencia INTEGER
        CHECK (tiempo_permanencia IS NULL OR tiempo_permanencia >= 1),

    CONSTRAINT chk_estancia_fechas CHECK (
        fecha_hora_salida IS NULL
        OR fecha_hora_salida >= fecha_hora_entrada
    ),
    CONSTRAINT chk_estancia_estado CHECK (
        (estado = 'activa'
         AND fecha_hora_salida IS NULL
         AND tiempo_permanencia IS NULL)
        OR
        (estado = 'finalizada'
         AND fecha_hora_salida IS NOT NULL
         AND tiempo_permanencia IS NOT NULL)
    )
);

-- Solo una estancia activa por vehiculo
CREATE UNIQUE INDEX IF NOT EXISTS idx_estancia_vehiculo_activo
ON public.estancias (vehiculo_id)
WHERE estado = 'activa';

-- Solo una estancia activa por espacio
CREATE UNIQUE INDEX IF NOT EXISTS idx_estancia_espacio_activo
ON public.estancias (espacio_id)
WHERE estado = 'activa';

-- 7. PAGOS
CREATE TABLE IF NOT EXISTS public.pagos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estancia_id BIGINT NOT NULL UNIQUE
        REFERENCES public.estancias(id)
        ON DELETE RESTRICT,
    valor NUMERIC(12,2) NOT NULL CHECK (valor > 0),
    fecha_pago TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    metodo_pago VARCHAR(50) NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'pagado'
        CHECK (estado = 'pagado')
);

-- 8. INDICES
CREATE INDEX IF NOT EXISTS idx_vehiculos_conductor
ON public.vehiculos(conductor_id);

CREATE INDEX IF NOT EXISTS idx_estancias_vehiculo
ON public.estancias(vehiculo_id);

CREATE INDEX IF NOT EXISTS idx_estancias_espacio
ON public.estancias(espacio_id);

CREATE INDEX IF NOT EXISTS idx_pagos_estancia
ON public.pagos(estancia_id);

